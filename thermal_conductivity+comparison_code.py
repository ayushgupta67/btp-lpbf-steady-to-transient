# 2. Network — sinusoidal timestep embedding (fixes the "stuck at 1.0" bug)
class SinusoidalTimeEmbedding(nn.Module):
    """Standard diffusion-style sinusoidal embedding for the discrete timestep tau."""
    def __init__(self, dim):
        super().__init__()
        self.dim = dim

    def forward(self, tau):
        half = self.dim // 2
        freqs = torch.exp(-math.log(10000) * torch.arange(half, device=tau.device).float() / half)
        args = tau.float()[:, None] * freqs[None, :]
        return torch.cat([torch.sin(args), torch.cos(args)], dim=-1)


class DiffMLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.time_embed = SinusoidalTimeEmbedding(32)
        self.time_mlp = nn.Sequential(nn.Linear(32, 32), nn.SiLU())
        self.net = nn.Sequential(
            nn.Linear(11 * 2 + 1 + 32, 256), nn.SiLU(),
            nn.Linear(256, 256), nn.SiLU(),
            nn.Linear(256, 256), nn.SiLU(),
            nn.Linear(256, 11)
        )

    def forward(self, x_tau, tau, t_phys, T_ss):
        t_emb = self.time_mlp(self.time_embed(tau))
        return self.net(torch.cat([x_tau, T_ss, t_phys, t_emb], dim=1))


steps = 1000
alpha_bar = torch.cumprod(1.0 - torch.linspace(1e-4, 0.02, steps).to(device), dim=0)


def q_sample(x_start, tau, noise):
    return torch.sqrt(alpha_bar[tau])[:, None] * x_start + torch.sqrt(1 - alpha_bar[tau])[:, None] * noise


# 3. Shared training loop helper (with early stopping to save time)
def run_training(model, optimizer, physics=False, epochs=150, patience=20, tag="model"):
    scaler = torch.cuda.amp.GradScaler(enabled=USE_AMP)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=8)

    best_loss = float("inf")
    epochs_no_improve = 0
    dx = 0.2 / 10.0
    t0 = time.time()

    for epoch in range(epochs):
        loss_sum = 0.0
        for T_tr, T_ss, t_ph in dataloader:
            T_tr, T_ss = T_tr.to(device), T_ss.to(device)
            t_ph = t_ph.to(device)
            if physics:
                t_ph = t_ph.requires_grad_(True)

            tau = torch.randint(0, steps, (T_tr.shape[0],), device=device)
            noise = torch.randn_like(T_tr)
            x_tau = q_sample(T_tr, tau, noise)

            optimizer.zero_grad(set_to_none=True)

            with torch.cuda.amp.autocast(enabled=USE_AMP):
                pred_noise = model(x_tau, tau, t_ph, T_ss)
                loss_data = nn.functional.mse_loss(pred_noise, noise)

            if physics:
                # Physics penalty only makes sense where the sample is still close to
                # the real signal (low tau => small noise). At high tau, alpha_bar is
                # ~1e-5 and dividing by sqrt(alpha_bar) blows small errors up by ~100-300x,
                # which is what caused the millions-scale loss before. Masking fixes that.
                pred_T = (x_tau - torch.sqrt(1 - alpha_bar[tau])[:, None] * pred_noise) / torch.sqrt(alpha_bar[tau])[:, None]
                pred_T = torch.clamp(pred_T, -3.0, 3.0)  # safety clamp against outliers
                mask = (tau < 200).float().unsqueeze(1)

                dT_dt = torch.autograd.grad(pred_T.sum(), t_ph, create_graph=True)[0]
                dT_dxx = (pred_T[:, 2:] - 2 * pred_T[:, 1:-1] + pred_T[:, :-2]) / (dx ** 2)
                loss_physics = torch.mean(mask * (dT_dt - dT_dxx.mean(dim=1, keepdim=True)) ** 2)

                loss = loss_data + 0.01 * loss_physics
            else:
                loss = loss_data

            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
            scaler.step(optimizer)
            scaler.update()

            loss_sum += loss.item()

        avg_loss = loss_sum / len(dataloader)
        scheduler.step(avg_loss)

        if avg_loss < best_loss - 1e-4:
            best_loss = avg_loss
            epochs_no_improve = 0
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
        else:
            epochs_no_improve += 1

        if (epoch + 1) % 10 == 0 or epoch == 0:
            print(f"[{tag}] Epoch {epoch+1}/{epochs}  Loss: {avg_loss:.4f}  "
                  f"BestLoss: {best_loss:.4f}  Elapsed: {time.time()-t0:.0f}s")

        if epochs_no_improve >= patience:
            print(f"[{tag}] Early stopping at epoch {epoch+1} (no improvement for {patience} epochs)")
            break

    model.load_state_dict(best_state)  # keep the best checkpoint, not just the last one
    print(f"[{tag}] Done in {time.time()-t0:.0f}s. Best loss: {best_loss:.4f}")
    return model

