alpha = 1.0 - torch.linspace(1e-4, 0.02, steps).to(device)

@torch.no_grad()
def sample(model, T_ss, t_phys):
    model.eval()
    img = torch.randn((1, 11), device=device)
    for i in reversed(range(steps)):
        tau = torch.full((1,), i, device=device, dtype=torch.long)
        pred_noise = model(img, tau, t_phys, T_ss)
        a_t, a_bar_t = alpha[tau][:, None], alpha_bar[tau][:, None]
        noise = torch.randn_like(img) if i > 0 else torch.zeros_like(img)
        img = 1 / torch.sqrt(a_t) * (img - ((1 - a_t) / torch.sqrt(1 - a_bar_t)) * pred_noise) + torch.sqrt(1 - a_t) * noise
    return img

@torch.no_grad()
def sample_multi(model, T_ss, t_phys, n=10):
    """Average n independent reverse-diffusion draws to remove single-sample luck."""
    preds = torch.stack([sample(model, T_ss, t_phys) for _ in range(n)])
    return preds.mean(dim=0).cpu().numpy().flatten()

