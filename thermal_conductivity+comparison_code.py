class ThermalDataset(Dataset):
    def __init__(self):
        data = scipy.io.loadmat('/content/drive/MyDrive/BTP_Diffusion/thermal_diffusion_dataset.mat')
        Y_all, conf, times, steady = data['Y_all'], data['config_ID_all'].flatten(), data['time_all'].flatten(), data['steady_flag_all'].flatten()

        self.transient_T, self.steady_T, self.phys_times = [], [], []
        for i in range(1, int(conf.max()) + 1):
            idx = (conf == i)
            T_ss = Y_all[:, idx][:, steady[idx] == 1].flatten()
            T_trans = Y_all[:, idx][:, steady[idx] == 0]
            t_trans = times[idx][steady[idx] == 0]
            for j in range(T_trans.shape[1]):
                self.transient_T.append(T_trans[:, j])
                self.steady_T.append(T_ss)
                self.phys_times.append(t_trans[j])

        self.transient_T = np.array(self.transient_T, dtype=np.float32)
        self.steady_T = np.array(self.steady_T, dtype=np.float32)
        self.phys_times = np.array(self.phys_times, dtype=np.float32).reshape(-1, 1) / 30000.0

        self.T_min = min(self.transient_T.min(), self.steady_T.min())
        self.T_max = max(self.transient_T.max(), self.steady_T.max())
        self.transient_T = 2 * ((self.transient_T - self.T_min) / (self.T_max - self.T_min)) - 1
        self.steady_T = 2 * ((self.steady_T - self.T_min) / (self.T_max - self.T_min)) - 1

    def __len__(self):
        return len(self.transient_T)

    def __getitem__(self, idx):
        return self.transient_T[idx], self.steady_T[idx], self.phys_times[idx]


