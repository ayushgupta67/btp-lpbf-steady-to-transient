"""Hybrid model: physics-style amplitude x diffusion shape, evaluated with the same
leave-one-setting-out folds as bead2_train.py.

    python -u bead2_hybrid.py

Why: the data analysis showed that (1) the field is exactly 65 C everywhere one time unit
after the scan ends (heat_end = 2 + 3.2 / v), so only t = 2 (all runs) and t = 3 (v = 10 only)
carry any signal, and (2) the t = 2 fields are one fixed shape times an amplitude. The plain
diffusion model has to learn both from 156 rows, 2/3 of which are all-ambient. Here

    field = 65 + A(q, v, t) * shape(steady field, P, v, hatch, t)

* rows after the cooling window are ambient by the rule above (no model needed),
* A is a log-quadratic fit of the peak rise in ln(P/hatch) and ln(v), per time t,
* shape = rise / peak (peak = 1) is generated by the conditional diffusion model.
Everything that depends on held-out data is recomputed inside each fold.
"""

import csv
import json
import time
from concurrent.futures import ProcessPoolExecutor
from multiprocessing import get_context
from pathlib import Path

import numpy as np
import torch

import bead2_data as bd
import bead_model as bm
from bead2_train import baselines, group_key, make_xy, rmse_pair, z_clip_for

OUT = Path(__file__).parent / "bead2_outputs"
BASE_T = bd.BASE_T
SCALE = 100.0  # shape in [0, 1] is stored as a temperature 65 + 100 * shape for the diffusion code
_G = {}


def has_signal(params, t):
    """True while the field is still above ambient: until one time unit after the scan ends."""
    v = params[:, 1]
    return (t - (2.0 + 3.2 / v)) < 1.0 - 1e-6


def _feat(p):
    lq, lv = np.log(p[0] / p[2]), np.log(p[1])
    return np.array([lq, lv, lq * lq, lv * lv, lq * lv])


def amp_fit(pairs, rows):
    """Per target time: ln(peak rise) = quadratic in (ln q, ln v), ridge on standardised features.
    The quadratic terms cut the cross-validated peak error from 3.0 % to 0.5 % (see README)."""
    fits = {}
    for t in sorted(set(pairs["t_target"][rows])):
        r = rows[pairs["t_target"][rows] == t]
        amp = (pairs["y"][r] - BASE_T).max(1)
        r, amp = r[amp > 0.5], amp[amp > 0.5]
        if len(r) < 3:
            continue
        X = np.stack([_feat(pairs["params"][i]) for i in r])
        keep = X.std(0) > 1e-9
        mu, sd = X[:, keep].mean(0), X[:, keep].std(0)
        Xs = np.column_stack([np.ones(len(r)), (X[:, keep] - mu) / sd])
        pen = np.diag([0.0] + [1e-3] * int(keep.sum()))
        c = np.linalg.solve(Xs.T @ Xs + pen, Xs.T @ np.log(amp))
        fits[int(t)] = dict(keep=keep, mu=mu, sd=sd, c=c)
    return fits


def amp_predict(fits, params, t_target):
    out = np.zeros(len(params))
    for i, (p, t) in enumerate(zip(params, t_target)):
        f = fits.get(int(t))
        if f is None:
            continue
        x = _feat(p)[f["keep"]]
        out[i] = np.exp(np.concatenate([[1.0], (x - f["mu"]) / f["sd"]]) @ f["c"])
    return out


def shapes_of(pairs, rows):
    rise = pairs["y"][rows] - BASE_T
    amp = rise.max(1)
    return rise / amp[:, None], amp


def _init(pairs, epochs, draws, ddim, seed, threads):
    torch.set_num_threads(threads)
    _G.update(pairs=pairs, epochs=epochs, draws=draws, ddim=ddim, seed=seed)


def hybrid_predict(P, train, test, epochs, draws, ddim, seed):
    """Train on signal rows of `train`; return (pred for `test`, extras)."""
    sig_tr = train[has_signal(P["params"][train], P["t"][train])]
    fits = amp_fit(P, sig_tr)
    shp, _ = shapes_of(P, sig_tr)
    cond = bm.cond_vector(P["steady"][sig_tr], P["params"][sig_tr], P["t"][sig_tr])
    z = bm.to_z(BASE_T + SCALE * shp).astype(np.float32)
    torch.manual_seed(seed)
    m = bm.BeadDiffusion(P["y"].shape[1])
    t0 = time.time()
    curve = bm.train(m, cond, z, epochs=epochs)
    t_train = time.time() - t0
    pred = np.full((len(test), P["y"].shape[1]), BASE_T)
    sig_te = has_signal(P["params"][test], P["t"][test])
    amp = amp_predict(fits, P["params"][test], P["t_target"][test])
    if sig_te.any():
        tt = test[sig_te]
        c_te = bm.cond_vector(P["steady"][tt], P["params"][tt], P["t"][tt])
        d = bm.sample(m, c_te, z_clip=z_clip_for(z), n_steps=ddim, n_draws=draws, seed=seed).mean(0)
        s = np.clip((d - BASE_T) / SCALE, -0.2, 1.5)
        s = s / np.maximum(s.max(1, keepdims=True), 1e-6)  # peak = 1 by definition
        pred[sig_te] = BASE_T + amp[sig_te][:, None] * s
    return pred, fits, m, z, curve, t_train


def amp_shape_same_v(P, train, test):
    """Baseline: same amplitude model, shape = mean normalised shape of training rows with the same v and t."""
    sig_tr = train[has_signal(P["params"][train], P["t"][train])]
    fits = amp_fit(P, sig_tr)
    shp, _ = shapes_of(P, sig_tr)
    pred = np.full((len(test), P["y"].shape[1]), BASE_T)
    amp = amp_predict(fits, P["params"][test], P["t_target"][test])
    for j, i in enumerate(test):
        if not has_signal(P["params"][i:i + 1], P["t"][i:i + 1])[0]:
            continue
        sel = (P["t_target"][sig_tr] == P["t_target"][i]) & (P["params"][sig_tr][:, 1] == P["params"][i][1])
        if sel.any():
            pred[j] = BASE_T + amp[j] * shp[sel].mean(0)
    return pred


def amp_shape_lnq(P, train, test):
    """Strongest simple model: quadratic amplitude x shape that is linear in ln q within the same v and t."""
    sig_tr = train[has_signal(P["params"][train], P["t"][train])]
    fits = amp_fit(P, sig_tr)
    shp, _ = shapes_of(P, sig_tr)
    pred = np.full((len(test), P["y"].shape[1]), BASE_T)
    amp = amp_predict(fits, P["params"][test], P["t_target"][test])
    for j, i in enumerate(test):
        if not has_signal(P["params"][i:i + 1], P["t"][i:i + 1])[0]:
            continue
        sel = (P["t_target"][sig_tr] == P["t_target"][i]) & (P["params"][sig_tr][:, 1] == P["params"][i][1])
        if sel.sum() >= 2:
            lq = np.log(P["params"][sig_tr][sel][:, 0] / P["params"][sig_tr][sel][:, 2])
            A = np.column_stack([np.ones(len(lq)), lq - lq.mean()])
            W = np.linalg.lstsq(A, shp[sel], rcond=None)[0]
            s_new = np.array([1.0, np.log(P["params"][i][0] / P["params"][i][2]) - lq.mean()]) @ W
            s_new = np.clip(s_new, -0.2, 1.5)
            pred[j] = BASE_T + amp[j] * s_new / max(s_new.max(), 1e-6)
        elif sel.any():
            pred[j] = BASE_T + amp[j] * shp[sel].mean(0)
    return pred


def _fold(args):
    f, key, test, train = args
    P = _G["pairs"]
    pred, *_rest, t_train = hybrid_predict(P, train, test, _G["epochs"], _G["draws"], _G["ddim"], _G["seed"] + 1 + f)
    preds = {"hybrid v2: quadratic amplitude x diffusion shape": pred, "amplitude x shape (same v)": amp_shape_same_v(P, train, test),
             "amplitude x shape (linear in ln q, same v)": amp_shape_lnq(P, train, test)}
    rows = []
    for name, p in preds.items():
        for j, i in enumerate(test):
            rows.append({"held_out_setting": f"q={key[0]}_v={key[1]:g}", "run": P["case"][i], "P": P["params"][i][0],
                         "v": P["params"][i][1], "hatch": P["params"][i][2], "t_target": int(P["t_target"][i]),
                         "t_actual": float(P["t"][i]), "method": name, **rmse_pair(p[j], P["y"][i])})
    return f, rows, t_train, pred, test


def main(epochs=1500, draws=8, ddim=50, seed=0, workers=3, threads=4):
    t_all = time.time()
    data = bd.load_cases()
    pairs = bd.build_pairs(data)
    mask = bd.active_node_mask(data)
    pairs["steady"], pairs["y"] = pairs["steady"][:, mask], pairs["y"][:, mask]
    n = len(pairs["case"])
    sig = has_signal(pairs["params"], pairs["t"])
    truth_sig = (pairs["y"] - BASE_T).max(1) > 0.5
    print(f"rule check: {int(sig.sum())} rows with signal by the cooling-window rule, {int(truth_sig.sum())} by the data; "
          f"mismatches: {int((sig != truth_sig).sum())}")
    keys = [group_key(p) for p in pairs["params"]]
    settings = sorted(set(keys))
    jobs = [(f, k, np.array([i for i, kk in enumerate(keys) if kk == k]), np.array([i for i, kk in enumerate(keys) if kk != k]))
            for f, k in enumerate(settings)]

    results, held = [], np.zeros_like(pairs["y"])
    t_cv = time.time()
    with ProcessPoolExecutor(workers, mp_context=get_context("spawn"), initializer=_init,
                             initargs=(pairs, epochs, draws, ddim, seed, threads)) as ex:
        for f, rows, t_train, pred, test in ex.map(_fold, jobs):
            results += rows
            held[test] = pred
            print(f"[hybrid cv {f + 1:2d}/{len(jobs)}] {jobs[f][1]} train {t_train:.0f}s", flush=True)
    t_cv = time.time() - t_cv
    with open(OUT / "cv_hybrid_v2_results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(results[0]))
        w.writeheader()
        w.writerows(results)
    np.savez_compressed(OUT / "cv_hybrid_v2_predictions.npz", pred=held, true=pairs["y"], t_target=pairs["t_target"],
                        params=pairs["params"], run=np.array(pairs["case"]))
    print(f"[hybrid cv] wall {t_cv / 60:.1f} min")

    # final hybrid model on all rows, saved
    torch.set_num_threads(8)
    allrows = np.arange(n)
    t0 = time.time()
    _, fits, m, z, curve, _t = hybrid_predict(pairs, allrows, allrows[:1], epochs, draws, ddim, seed)
    t_final = time.time() - t0
    meta = {"kind": "hybrid amplitude x diffusion shape", "epochs": epochs, "ddim_steps": ddim, "draws": draws,
            "z_clip": z_clip_for(z), "shape_scale": SCALE, "param_scale": bm.PARAM_SCALE.tolist(), "asinh_knee": bm.ASINH_KNEE,
            "z_div": bm.Z_DIV, "t_offset": bm.T_OFFSET, "t_span": bm.T_SPAN, "steps": bm.STEPS, "n_nodes": int(mask.sum()),
            "active_node_indices": np.flatnonzero(mask).tolist(), "final_loss": curve[-1], "train_seconds": t_final,
            "amplitude_fit": {str(t): {"keep": f["keep"].tolist(), "mu": f["mu"].tolist(), "sd": f["sd"].tolist(), "c": f["c"].tolist()}
                              for t, f in fits.items()},
            "rule": "ambient (65) when t - (2 + 3.2/v) >= 1.0"}
    bm.save_checkpoint(OUT / "model" / "bead2_hybrid_v2.pt", m, meta)
    (OUT / "model" / "hybrid_v2_meta.json").write_text(json.dumps({k: v for k, v in meta.items() if k != "active_node_indices"}, indent=2))
    print(f"[hybrid final] {t_final:.0f}s, saved; total {(time.time() - t_all) / 60:.1f} min")


if __name__ == "__main__":
    main()
